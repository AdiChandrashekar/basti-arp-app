const SUBJECTS = {
  hi: { Hindi: 'हिंदी', Maths: 'गणित', English: 'अंग्रेज़ी', Science: 'विज्ञान', 'Social Studies': 'सामाजिक विज्ञान', EVS: 'पर्यावरण अध्ययन', Other: 'अन्य' },
  en: {},
}

export function makeT(lang, meta) {
  const s = STRINGS[lang] || STRINGS.en
  const kpiLabel = Object.fromEntries(meta.kpis.map((k) => [k.id, KPI[lang]?.[k.id] || KPI.en[k.id] || k.label]))
  const t = {
    ...s,
    lang,
    kpi: (id) => kpiLabel[id],
    subject: (x) => (x ? SUBJECTS[lang]?.[x] || x : ''),
    month: (m) => {
      const [y, mm] = m.split('-')
      return `${MONTHS[lang][+mm - 1]} ${y}`
    },
    monthName: (m) => MONTHS[lang][+m.split('-')[1] - 1],
    monthShort: (m) => MONTHS_SHORT[lang][+m.split('-')[1] - 1],
    date: (d) => {
      const [y, m, dd] = d.split('-')
      return `${+dd} ${MONTHS[lang][+m - 1]} ${y}`
    },
    dayDate: (d) => {
      const [y, m, dd] = d.split('-').map(Number)
      return `${WEEKDAYS[lang][new Date(y, m - 1, dd).getDay()]}, ${dd} ${MONTHS[lang][m - 1]}`
    },
    dayShort: (d) => {
      const [y, m, dd] = d.split('-').map(Number)
      return `${WEEKDAYS_SHORT[lang][new Date(y, m - 1, dd).getDay()]} ${dd}`
    },
    weekHead: lang === 'hi' ? ['सो', 'मं', 'बु', 'गु', 'शु', 'श', 'र'] : ['M', 'T', 'W', 'T', 'F', 'S', 'S'],
  }
  return t
}
